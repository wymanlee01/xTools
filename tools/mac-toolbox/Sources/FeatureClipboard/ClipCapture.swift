import AppKit
import ToolboxCore

/// 剪贴板 ↔ 历史记录的转换
public enum ClipCapture {
    /// 不记录的类型：密码管理器等标记的隐藏 / 临时 / 自动生成内容（nspasteboard.org 约定）
    public static let skippedTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    public struct Options {
        public var recordImages = true
        public var recordFiles = true
        public init(recordImages: Bool = true, recordFiles: Bool = true) {
            self.recordImages = recordImages
            self.recordFiles = recordFiles
        }
    }

    /// 读取剪贴板生成一条记录；不该记录（隐藏内容、空内容、被关闭的类型）时返回 nil
    /// 图片、富文本写进 store 的目录
    public static func read(_ board: NSPasteboard, store: ClipStore, options: Options,
                            source: NSRunningApplication?) -> ClipItem? {
        let types = board.types ?? []
        if types.contains(where: skippedTypes.contains) { return nil }
        let origin = board.string(forType: PasteboardService.sourceType)
        func make(_ kind: ClipItem.Kind, text: String = "", data: Data) -> ClipItem {
            ClipItem(kind: kind, text: text, sourceBundleID: source?.bundleIdentifier, sourceName: source?.localizedName,
                     origin: origin, fingerprint: ClipItem.fingerprint(kind: kind, data: data))
        }

        // 1. 文件（Finder 里复制的文件）
        if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            guard options.recordFiles else { return nil }
            let paths = urls.map(\.path)
            var item = make(.files, text: paths.map { ($0 as NSString).lastPathComponent }.joined(separator: "\n"),
                            data: Data(paths.joined(separator: "\n").utf8))
            item.filePaths = paths
            return item
        }

        // 2. 图片（截图、浏览器里复制的图片）
        if types.contains(.png) || types.contains(.tiff), board.string(forType: .string) == nil {
            guard options.recordImages,
                  let image = NSImage(pasteboard: board),
                  let tiff = image.tiffRepresentation,
                  let rep = NSBitmapImageRep(data: tiff),
                  let png = rep.representation(using: .png, properties: [:]) else { return nil }
            var item = make(.image, data: png)
            let file = "\(item.id.uuidString).png"
            guard (try? png.write(to: store.imagesDirectory.appendingPathComponent(file))) != nil else { return nil }
            item.imageFile = file
            item.imageWidth = rep.pixelsWide
            item.imageHeight = rep.pixelsHigh
            return item
        }

        // 3. 文字（保留富文本，粘贴时可选纯文本）
        guard let text = board.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        var item = make(.text, text: text, data: Data(text.utf8))
        if let rtf = board.data(forType: .rtf) {
            let file = "\(item.id.uuidString).rtf"
            if (try? rtf.write(to: store.rtfDirectory.appendingPathComponent(file))) != nil { item.rtfFile = file }
        }
        return item
    }

    /// 把记录还原成剪贴板内容；plainText 为 true 时文字只写纯文本
    public static func pasteboardItems(for item: ClipItem, store: ClipStore, plainText: Bool) -> [NSPasteboardItem] {
        switch item.kind {
        case .text:
            let pbItem = NSPasteboardItem()
            pbItem.setString(item.text, forType: .string)
            if !plainText, let url = store.rtfURL(for: item), let rtf = try? Data(contentsOf: url) {
                pbItem.setData(rtf, forType: .rtf)
            }
            return [pbItem]
        case .image:
            guard let url = store.imageURL(for: item), let png = try? Data(contentsOf: url) else { return [] }
            let pbItem = NSPasteboardItem()
            pbItem.setData(png, forType: .png)
            if let tiff = NSImage(data: png)?.tiffRepresentation { pbItem.setData(tiff, forType: .tiff) }
            return [pbItem]
        case .files:
            return item.filePaths.map { path in
                let pbItem = NSPasteboardItem()
                pbItem.setString(URL(fileURLWithPath: path).absoluteString, forType: .fileURL)
                return pbItem
            }
        }
    }
}
